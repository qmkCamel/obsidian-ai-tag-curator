// Bundles the Obsidian plugin entry into the root main.js file.
import esbuild from "esbuild";
import { builtinModules } from "node:module";
import process from "node:process";
import { resolve } from "node:path";
import { readFileSync } from "node:fs";

const production = process.argv[2] === "production";
const d3Modules=Object.keys(JSON.parse(readFileSync("package-lock.json","utf8")).packages).filter(name=>/^node_modules\/d3-[^/]+$/.test(name)).sort();
const thirdPartyNotices=d3Modules.map(name=>`${name.replace("node_modules/","")}\n${readFileSync(`${name}/LICENSE`,"utf8")}`).join("\n\n");

// The worker is rebuilt and embedded on every main rebuild; no fourth release asset.
const graphWorkerPlugin = {
  name: "embedded-tag-graph-worker",
  setup(build) {
    build.onLoad({filter:/[\\/]graph[\\/]worker-source\.ts$/}, async () => {
      const worker = await esbuild.build({entryPoints:["src/graph/tag-graph.worker.ts"],bundle:true,write:false,format:"iife",platform:"browser",target:"es2018",minify:true,metafile:true});
      return {contents:`export default ${JSON.stringify(worker.outputFiles[0].text)}`,loader:"js",watchFiles:Object.keys(worker.metafile.inputs).map(file=>resolve(file))};
    });
  }
};

const context = await esbuild.context({
  banner: {
    js: `/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD\nThird-party runtime licenses:\n${thirdPartyNotices.replace(/\*\//g,"* /")}\n*/`
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  plugins: [graphWorkerPlugin],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
    ...builtinModules.map((moduleName) => `node:${moduleName}`)
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: production
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
